// The token-usage plugin still supports hosts from before the translation SDK.
const messages = typeof defineTranslations === "function" && typeof useTranslation === "function"
  ? defineTranslations({ resources: { en, "zh-CN": zh } }) : null;

type Labels = (key: keyof typeof en, options?: { value: string }) => string;

export const useSpeedMessages: () => { t: Labels; locale: string } = messages
  ? () => useTranslation(messages)
  : () => ({ t: (key, options) => en[key].replace("{{value}}", options?.value ?? ""), locale: "en" });

export const usageSettingsTitle = messages?.message("settings") ?? en.settings;
