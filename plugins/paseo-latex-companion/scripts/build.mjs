import { readFile, writeFile } from "node:fs/promises";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { build, transform } from "esbuild";

const root = new URL("../", import.meta.url);
const dist = new URL("node_modules/katex/dist/", root);
const original = await readFile(new URL("katex.min.css", dist), "utf8");
const fontFaces = original.match(/@font-face\{[^}]+\}/g);
if (!fontFaces?.length) throw new Error("KaTeX font-face rules missing");
const fonts = fontFaces.map(face => face.replace(/KaTeX_/g, "PaseoLatex_KaTeX_")
  .replace(/src:url\(fonts\/PaseoLatex_(KaTeX_[\w-]+\.woff2)\)[^}]*/, (_, file) => {
    const bytes = readFileSync(new URL("fonts/" + file, dist));
    return 'src:url(data:font/woff2;base64,' + bytes.toString("base64") + ') format("woff2")';
  })).join("\n");
if (/url\(fonts\//.test(fonts)) throw new Error("KaTeX font URL could not be embedded");
const rules = original.replace(/@font-face\{[^}]+\}/g, "").replaceAll("KaTeX_", "PaseoLatex_KaTeX_");
const css = await transform(fonts + "\n[data-paseo-latex] {" + rules + "}\n" +
  '[data-paseo-latex="display"] { display:block; max-width:100%; overflow-x:auto; overflow-y:hidden; }' +
  '[data-paseo-latex] .katex-display { margin: .35em 0; }', {
    loader: "css", target: "chrome90", minify: true,
  });

const web = await build({
  entryPoints: [fileURLToPath(new URL("client/web.ts", root))], bundle: true, write: false,
  platform: "browser", target: "es2020", format: "iife", globalName: "CompanionWeb",
  minify: true, legalComments: "none", define: { COMPANION_CSS: JSON.stringify(css.code) },
});
const entry = await readFile(new URL("client/entry.ts", root), "utf8");
// Paseo evaluates its own plugin bundles with Function. Keeping this static
// build output in a string also keeps native runtimes from parsing web code.
const factory = "function startWebCompanion(document) {\n" +
  "  const load = new Function(" + JSON.stringify(web.outputFiles[0].text + "\nreturn CompanionWeb.start;") + ");\n" +
  "  return load()(document);\n}\n";
const output = entry.replace("declare function startWebCompanion(document: Document): () => void;", factory);
await writeFile(new URL("index.client.ts", root), "// Generated by npm run build. Source is in client/.\n" + output);
